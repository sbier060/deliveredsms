/** The 3-digit area code of an E.164 NANP number, or null. */
export function npaOf(e164: string): string | null {
  const digits = e164.replace(/[^\d]/g, '');
  const ten = digits.length === 11 && digits.startsWith('1') ? digits.slice(1) : digits;
  return ten.length === 10 ? ten.slice(0, 3) : null;
}

/** True when the number is in a real US or Canadian area code. */
export function isUsOrCanadaNpa(e164: string): boolean {
  const npa = npaOf(e164);
  return npa !== null && (US_NPAS.has(npa) || CA_NPAS.has(npa));
}

